test(
  'real API v3, controlled metrics, three chained cores, scripts, cancellation and disconnection',
  { timeout: 300000 },
  async (t) => {
    const f = await fixture(t),
      kernels = new KernelManager(f.directory);
    await kernels.initialize();
    const lease = kernels.snapshot();
    assert.equal(lease.binaries.size, 3, 'Prepare the official kernels; do not skip chain checks');
    const net = await controlledNetwork(
      lease.binaries.get('singbox').path,
      join(f.directory, 'network'),
    );
    const backend = new MiaospeedClient(process.env.MIAOSPEED_URL, process.env.MIAOSPEED_TOKEN);
    f.beforeClose(async () => {
      await net.close();
      await lease.release();
      await kernels.close();
    });
    await assert.rejects(
      new MiaospeedClient(process.env.MIAOSPEED_URL, 'incorrect-test-token').run(
        net.settings,
        [],
        [],
        [],
        AbortSignal.timeout(10000),
        undefined,
        true,
      ),
    );
    const ids = metricIds.filter(
      (id) => !['TEST_PING_MAX_CONN', 'TEST_HIJACK_DETECTION'].includes(id),
    );
    const matrices = [
      ...ids.map((Type) => ({ Type, Params: '' })),
      { Type: 'TEST_SCRIPT', Params: net.script.ID },
    ];
    let progress = 0;
    const result = await backend.run(
      net.settings,
      [{ Name: net.raw.name, Payload: JSON.stringify(net.raw) }],
      matrices,
      [net.script, net.geoScript],
      AbortSignal.timeout(60000),
      () => {
        progress++;
      },
    );
    assert.equal(result.version, '4.7.6');
    assert.equal(result.slots.length, 1);
    assert.ok(progress > 0);
    const measured = measurements(
      result.slots[0],
      [...ids, 'TEST_PING_MAX_CONN'],
      [{ id: net.script.ID, name: 'Controlled' }],
    );
    const get = (id) => measured.find((m) => m.id === id);
    assert.equal(get('TEST_HTTP_CODE').value, '204, 204, 204', JSON.stringify(result.slots));
    for (const id of ['SPEED_AVERAGE', 'USPEED_AVERAGE', 'SPEED_PER_SECOND', 'USPEED_PER_SECOND']) {
      assert.equal(get(id).status, 'measured', JSON.stringify(result.slots));
      assert.ok(get(id).value > 0);
      assert.equal(get(id).unit, 'B/s');
    }
    assert.ok(net.counts.download > 100000);
    assert.ok(net.counts.upload > 100000);
    assert.equal(get('TEST_PING_PACKET_LOSS').value, 0);
    assert.equal(get('script:controlled').value, 'controlled-fixture');
    assert.equal(get('script:controlled').color, '#0c2238');
    assert.equal(get('GEOIP_OUTBOUND').geo[0].ip, '203.0.113.9');
    assert.equal(get('UDP_TYPE').status, 'measured', JSON.stringify(get('UDP_TYPE')));
    assert.ok(net.counts.stun >= 4);

    // Configurations are generated by the actual bundled file script in pinned Sub-Store.
    const resource = await f.nodes.create({
      name: 'miaospeed-chain',
      source: 'local',
      content: JSON.stringify({ proxies: [net.chain.entry, net.chain.exit].map(toUpstream) }),
    });
    const chain = await f.chains.create({
      name: 'controlled two-hop',
      enabled: true,
      entry: { resourceId: resource.id, nodeName: net.chain.entry.name },
      exit: { resourceId: resource.id, nodeName: net.chain.exit.name },
    });
    for (const core of ['mihomo', 'singbox', 'xray']) {
      const plan = await f.subscriptions.create({
        ...newSubscription(),
        name: 'chain-' + core,
        inputs: [{ kind: 'chain', id: chain.id }],
        formats: [core],
        listenPort: await freeBridgePort(),
      });
      const full = (await f.subscriptions.artifact(plan.id, core)).content;
      const port = plan.listenPort,
        abort = new AbortController();
      const bridge = await launchBridge(
        lease.binaries.get(core),
        full,
        port,
        f.directory,
        process.env.MIAOSPEED_BRIDGE_HOST,
        abort.signal,
      );
      try {
        const before = { ...net.counts };
        const output = await backend.run(
          net.settings,
          [{ Name: core, Payload: bridge.payload }],
          matrices,
          [net.script, net.geoScript],
          AbortSignal.timeout(60000),
        );
        const rows = measurements(output.slots[0], ids, []);
        for (const id of [
          'TEST_HTTP_CODE',
          'SPEED_AVERAGE',
          'USPEED_AVERAGE',
          'UDP_TYPE',
          'GEOIP_OUTBOUND',
        ])
          assert.equal(
            rows.find((m) => m.id === id).status,
            'measured',
            core +
              ': ' +
              id +
              ' ' +
              JSON.stringify(net.counts) +
              ' ' +
              bridge.diagnostics +
              ' ' +
              net.proxies.map((p) => p.log).join('\n'),
          );
        assert.ok(net.counts.stun > before.stun);
        assert.ok(net.counts.download > before.download);
        assert.ok(net.counts.upload > before.upload);
        net.assertTwoHops();
        const wrong = { ...JSON.parse(bridge.payload), password: 'incorrect-test-password' };
        const rejected = await backend.run(
          net.settings,
          [{ Name: 'wrong', Payload: JSON.stringify(wrong) }],
          [{ Type: 'TEST_HTTP_CODE', Params: '' }],
          [],
          AbortSignal.timeout(15000),
        );
        assert.notEqual(
          measurements(rejected.slots[0], ['TEST_HTTP_CODE'], [])[0].status,
          'measured',
        );
        const beforeHang = net.counts.http;
        const running = backend.run(
          {
            ...net.settings,
            pingUrl: `http://127.0.0.1:${net.port}/hang`,
            requestTimeoutMs: 10000,
          },
          [{ Name: core, Payload: bridge.payload }],
          [{ Type: 'TEST_HTTP_CODE', Params: '' }],
          [],
          abort.signal,
        );
        const cancelled = assert.rejects(running, (error) => error.code === 'TEST_CANCELLED');
        await waitFor(() => net.counts.http > beforeHang);
        abort.abort();
        await cancelled;
      } finally {
        abort.abort();
        await bridge.close();
      }
      assert.equal(
        await portReady(port, AbortSignal.timeout(1000)),
        false,
        'Cancelled core must release its listener',
      );
      assert.deepEqual(await readdir(join(f.directory, 'node-test-tmp')), []);
      await f.subscriptions.delete(plan.id, plan.revision);
    }

    // Every shipped script executes in the real backend VM and may honestly return restricted/unknown.
    const catalog = (await f.miaospeedScripts.initialize()).scripts;
    assert.equal(catalog.length, 16);
    assert.ok(catalog.every((s) => !s.modified));
    const external = await backend.run(
      { ...net.settings, timeoutSeconds: 240 },
      [{ Name: 'script-fixture', Payload: JSON.stringify(net.raw) }],
      [
        ...catalog.map((s) => ({ Type: 'TEST_SCRIPT', Params: s.id })),
        { Type: 'TEST_HIJACK_DETECTION', Params: '' },
      ],
      catalog.map(backendScript),
      AbortSignal.timeout(240000),
    );
    const scriptPayloads = external.slots[0].Matrices.filter((m) => m.Type === 'TEST_SCRIPT').map(
      (m) => JSON.parse(m.Payload),
    );
    assert.ok(external.slots[0].Matrices.some((m) => m.Type === 'TEST_HIJACK_DETECTION'));
    assert.deepEqual(new Set(scriptPayloads.map((m) => m.Key)), new Set(catalog.map((s) => s.id)));
    assert.ok(
      scriptPayloads.every((m) => typeof m.Text === 'string' && m.Text.trim()),
      'Every builtin must return a conclusion or explicit unknown',
    );
    console.info(
      'Builtin script outcomes:',
      JSON.stringify(
        measurements(external.slots[0], [], catalog).map((m) => ({
          name: m.label,
          status: m.status,
          text: m.value,
        })),
      ),
    );
    const name = process.env.SUBMELD_TEST_MIAOSPEED_CONTAINER;
    assert.ok(name.startsWith('submeld-test-'));
    const beforeHang = net.counts.http;
    const running = backend.run(
      { ...net.settings, pingUrl: `http://127.0.0.1:${net.port}/hang`, requestTimeoutMs: 10000 },
      [{ Name: 'disconnect', Payload: JSON.stringify(net.raw) }],
      [{ Type: 'TEST_HTTP_CODE', Params: '' }],
      [],
      AbortSignal.timeout(20000),
    );
    const disconnected = assert.rejects(running, (error) =>
      ['MIAOSPEED_DISCONNECTED', 'MIAOSPEED_UNAVAILABLE'].includes(error.code),
    );
    await waitFor(() => net.counts.http > beforeHang);
    execFileSync('docker', ['restart', name], { windowsHide: true, timeout: 30000 });
    await disconnected;
    await waitFor(async () => {
      try {
        return (
          (await backend.run(net.settings, [], [], [], AbortSignal.timeout(1000), undefined, true))
            .version === '4.7.6'
        );
      } catch {
        return false;
      }
    }, 15000);
  },
);

test('native temporary parsing, script revisions, sanitized reports and interrupted recovery', async (t) => {
  const f = await fixture(t);
  const raw = {
    name: 'native socks',
    type: 'socks5',
    server: 'example.com',
    port: 1080,
    username: 'fixture',
    password: 'never-in-report',
    udp: true,
  };
  const before = await f.client.api('/api/subs');
  const preview = await f.miaospeedInput.preview({
    kind: 'text',
    content: JSON.stringify({ proxies: [raw, { name: 'invalid', type: 'unrecognized' }] }),
  });
  assert.equal(preview.nodes.length, 2);
  assert.ok(preview.nodes[1].error);
  const ref = { kind: 'temporary', previewId: preview.id, nodeIndex: 0 };
  assert.equal(
    JSON.parse(await f.miaospeedInput.payload(f.miaospeedInput.capture(ref).raw, 'test')).password,
    raw.password,
  );
  assert.deepEqual(await f.client.api('/api/subs'), before);
  let now = 0;
  const input = new MiaospeedInput(f.resources, f.chains, () => now);
  const expired = await input.preview({
    kind: 'file',
    content: JSON.stringify({ proxies: [raw] }),
  });
  now = 31 * 60 * 1000;
  assert.throws(
    () => input.capture({ kind: 'temporary', previewId: expired.id, nodeIndex: 0 }),
    /过期/,
  );
  input.close();
  const scripts = (await f.miaospeedScripts.initialize()).scripts;
  const script = scripts[0],
    data = scriptConfigSchema.strip().parse(script);
  const updated = (
    await f.miaospeedScripts.put(
      { ...data, content: 'function handler(){return {text:"custom"}}', revision: script.revision },
      script.id,
    )
  ).scripts.find((s) => s.id === script.id);
  assert.ok(updated.modified);
  assert.equal(
    (await f.miaospeedScripts.initialize()).scripts.find((s) => s.id === script.id).content,
    updated.content,
  );
  await assert.rejects(
    f.miaospeedScripts.put({ ...data, revision: script.revision }, script.id),
    /修改/,
  );
  const kernels = new KernelManager(f.directory);
  await kernels.initialize();
  const tester = new MiaospeedTester(
    f.miaospeedStore,
    f.miaospeedScripts,
    f.miaospeedInput,
    kernels,
    f.converter,
    f.testActivity,
    f.config,
  );
  f.beforeClose(async () => {
    await tester.close();
    await kernels.close();
  });
  const only = { ...data, content: 'function handler(){return {text:"completed"}}' };
  const added = (await f.miaospeedScripts.put(only)).scripts.find((s) => !s.builtinId);
  const report = await tester.start({
    subjects: [ref],
    metrics: [],
    scripts: [{ id: added.id, revision: added.revision }],
    settings: speedSettingsSchema.parse({}),
  });
  assert.throws(() => f.testActivity.acquire('three-core'), /测试/);
  assert.throws(() => f.miaospeedInput.capture(ref), /过期/);
  await waitFor(() => f.miaospeedStore.get(report.id).state !== 'running', 15000);
  const saved = f.miaospeedStore.get(report.id);
  assert.equal(saved.state, 'completed');
  assert.equal(saved.results[0].measurements[0].value, 'completed');
  assert.ok(!JSON.stringify(saved).includes(raw.password));
  assert.ok(!JSON.stringify(saved).includes('Payload'));
  assert.ok(!JSON.stringify(saved).includes('example.com'));
  const db = new Database(join(f.directory, 'submeld-v2.sqlite'));
  try {
    saved.state = 'running';
    saved.results[0].state = 'running';
    f.miaospeedStore.create(saved);
    const recovery = new MiaospeedStore(db);
    assert.equal(recovery.get(saved.id).state, 'interrupted');
    assert.equal(recovery.get(saved.id).results[0].state, 'cancelled');
    recovery.remove(saved.id);
    assert.equal(db.prepare('SELECT COUNT(*) n FROM speed_results').get().n, 0);
  } finally {
    db.close();
  }
  const bytes = await readFile(join(f.directory, 'submeld-v2.sqlite'));
  assert.ok(!bytes.includes(Buffer.from(raw.password)));
  const resource = await f.nodes.create({
    name: 'stale-speed',
    source: 'local',
    content: JSON.stringify({ proxies: [raw] }),
  });
  const node = (await f.nodes.list(resource.id)).nodes[0];
  const slow = (
    await f.miaospeedScripts.put(
      {
        ...scriptConfigSchema.strip().parse(added),
        content:
          'function handler(){var end=Date.now()+1000;while(Date.now()<end){} return {text:"completed"}}',
        revision: added.revision,
      },
      added.id,
    )
  ).scripts.find((s) => s.id === added.id);
  const changed = await tester.start({
    subjects: [subject(node)],
    metrics: [],
    scripts: [{ id: slow.id, revision: slow.revision }],
    settings: speedSettingsSchema.parse({}),
  });
  await waitFor(() => f.miaospeedStore.get(changed.id).results[0].state === 'running');
  await f.client.api(
    '/api/sub/' + resource.upstreamName,
    { content: JSON.stringify({ proxies: [{ ...raw, port: 1081 }] }) },
    'PATCH',
  );
  await waitFor(() => f.miaospeedStore.get(changed.id).state !== 'running');
  const historical = await tester.report(changed.id);
  assert.equal(historical.results[0].stale, true);
  assert.equal(historical.results[0].state, 'stale');
  assert.equal(historical.results[0].subject.snapshotHash, node.snapshotHash);
});

test('invalid matrices stay unknown and target anomalies never become node failures', async () => {
  const ids = ['SPEED_AVERAGE', 'TEST_PING_CONN', 'GEOIP_OUTBOUND', 'TEST_HTTP_CODE'];
  for (const slot of [
    { Matrices: [] },
    { Matrices: ids.map((Type) => ({ Type, Payload: 'null' })) },
    { Matrices: ids.map((Type) => ({ Type, Payload: '{"Value":0}' })) },
  ])
    assert.ok(measurements(slot, ids, []).every((m) => m.status === 'unknown'));
  for (const host of ['198.18.0.2', '127.0.0.1', 'does-not-exist.invalid'])
    await assert.rejects(
      validateTargets(
        speedSettingsSchema.parse({ pingUrl: 'https://' + host + '/' }),
        ['TEST_HTTP_CODE'],
        AbortSignal.timeout(5000),
      ),
      (error) => error.code === 'TEST_TARGET_ERROR',
    );
  assert.equal(bundledScripts().length, 16);
});
